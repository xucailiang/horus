"""Start the permanent fixture and prepare a clean real-host acceptance directory.

No plans or approvals are generated by this helper. It only supplies raw API input,
the shipped skill, isolated test credentials, and a persistent fixture to test.
"""

import json
import os
import shutil
import uuid
from pathlib import Path

from horus.core.store import atomic_write
from tests.fixtures.reference_api import ReferenceServer


def main() -> None:
    repository = Path(__file__).resolve().parents[2]
    demo = repository / ".horus-demo"
    demo.mkdir(exist_ok=True, mode=0o700)
    credentials_path = demo / "credentials.json"
    if not credentials_path.exists():
        atomic_write(
            credentials_path,
            {"HORUS_USERNAME": "fixture-" + uuid.uuid4().hex, "HORUS_PASSWORD": uuid.uuid4().hex},
        )
    credentials = json.loads(credentials_path.read_bytes())
    server = ReferenceServer(
        0,
        mode="normal",
        username=credentials["HORUS_USERNAME"],
        password=credentials["HORUS_PASSWORD"],
    )
    for host, skill_root in [("codex", ".agents"), ("claude", ".claude")]:
        destination = demo / host / skill_root / "skills" / "horus"
        shutil.copytree(repository / "skills/horus", destination, dirs_exist_ok=True)
    state = {"baseUrl": f"http://127.0.0.1:{server.server_port}", "fixturePid": os.getpid()}
    atomic_write(demo / "fixture.json", state)
    print(json.dumps(state), flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
